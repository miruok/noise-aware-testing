"""
Check that every number in the result tables of the paper matches the table
generated by make_tables.py from the raw results (to the precision printed in
the paper).
Usage: python check_paper_tables.py <paper>/sections [<paper>/supplement/supplement.tex]
Tables of the supplement carry the prefix "supp:" in their labels. Tables
without a generated counterpart (design and related-work tables) are listed
with "--".
Remaining differences are reported as CHK with the unmatched numbers; in the
submitted paper these are bug identifiers, draw totals summed over operators,
the sign-flip p = 0.125 printed as 0.12, and the sentinel's (m, alpha_s) label.
"""
import re, glob, os, sys
from decimal import Decimal
import argparse
ap = argparse.ArgumentParser(); ap.add_argument('paper_sections', help='folder with the LaTeX sections of the paper')
ap.add_argument('supplement', nargs='?', help='LaTeX file of the supplementary tables')
ARGS = ap.parse_args(); PAPER = ARGS.paper_sections
GEN = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'results', 'tables')
def tables(text):
    out={}
    for m in re.finditer(r'\\begin\{table\*?\}(.*?)\\end\{table\*?\}', text, re.S):
        body=m.group(1); lab=re.search(r'\\label\{([^}]*)\}', body)
        if lab:
            tab=re.search(r'\\begin\{tabular\}.*?\\end\{tabular\}', body, re.S)
            out[lab.group(1)]=tab.group(0) if tab else body
    return out
NUM=re.compile(r'(?<![\w.])(\d+(?:\{,\}\d+)?(?:\.\d+)?)(?:\s*\\times\s*10\^\{(-?\d+)\})?')
def nums(t):
    t=re.sub(r'\\(cmidrule|multicolumn|setlength|textsuperscript)\{[^}]*\}(\{[^}]*\})*','',t)
    t=re.sub(r'\{[lrcp@][^}]*\}','',t)
    res=[]
    for m in NUM.finditer(t):
        s=m.group(1).replace('{,}','')
        v=Decimal(s); e=m.group(2)
        if e: v=v*Decimal(10)**int(e)
        dec=len(s.split('.')[1]) if '.' in s else 0
        res.append((s if not e else s+'e'+e, v, dec))
    return res
P={}; [P.update(tables(open(f).read())) for f in sorted(glob.glob(PAPER+'/*.tex'))]
if ARGS.supplement:
    P.update({k.replace('supp:', '', 1): v for k, v in tables(open(ARGS.supplement).read()).items()})
G={}; [G.update(tables(open(f).read())) for f in sorted(glob.glob(GEN+'/*.tex'))]
alias={'tab:sobol':'tab:design-sobol','tab:rq4-realbugs':'tab:rq4-realbugs'}
for lab,pt in P.items():
    g=G.get(alias.get(lab,lab))
    if g is None: print(f'-- {lab}: no generated table'); continue
    gv=[v for _,v,_ in nums(g)]
    miss=[]
    for s,v,dec in nums(pt):
        tol=Decimal(5)*Decimal(10)**(-(dec+1)) if dec else Decimal('0.5')
        # allow percent forms
        cands=[v, v/100]
        if not any(abs(c-x)<=tol+Decimal('1e-12') or abs(c-x)<=abs(x)*Decimal('0.005') for c in cands for x in gv): miss.append(s)
    print(f'{"OK " if not miss else "CHK"} {lab}: {len(nums(pt))} numbers' + (f'; unmatched: {miss[:25]}' if miss else ''))
